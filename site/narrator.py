def _has(text: str, words: tuple[str, ...]) -> bool:
    return any(w in text for w in words)


def detect(action: str) -> tuple[str | None, int]:
    """Что за проверка стоит за действием. None — действие без броска."""
    low = action.lower()
    for words, skill, dc in RULES:
        if _has(low, words):
            return skill, dc
    return None, 0


def d20_text(check: dict) -> str:
    prof = " (владение)" if check.get("proficient") else ""
    return (f"d20 {check['natural']} {check['modifier']:+d}{prof} = {check['total']} "
            f"против Сл {check['dc']}")


