def _hits(n: int) -> str:
    """1 хит, 2–4 хита, 5+ хитов."""
    if n % 10 == 1 and n % 100 != 11:
        return "хит"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "хита"
    return "хитов"


def narrate(action: str, hero: dict, sheet: dict, abilities: dict,
            turn: int, seed: int | None = None) -> dict:
    """Один ход: что за проверка, её исход и проза мастера."""
    rng = random.Random(seed)
    skill, dc = detect(action)
    beat = rng.choice(BEATS)

    if skill is None:
        text = (f"Вы делаете то, что сказали. Мир отвечает без спешки: "
                f"{beat[0].lower() + beat[1:]}")
        return {"skill": None, "check": None, "text": text, "damage": 0}

    from heroes import resolve
    check = resolve(abilities, sheet, skill=skill, dc=dc,
                    seed=seed if seed is not None else rng.randrange(1, 10**6))
    label = SKILLS[skill][0]
    roll_line = d20_text(check)

    detail = (DETAIL_SUCCESS if check["success"] else DETAIL_FAIL)[skill]
    detail = detail[0].upper() + detail[1:]
    body = (rng.choice(SUCCESS) if check["success"] else rng.choice(FAIL)).format(detail=detail)

    damage = 0
    if not check["success"] and skill in HARM_ON_FAIL:
        damage = int(engine.roll_dice_str("1d4"))
        body += f" Вы теряете {damage} {_hits(damage)}."

    text = f"{body}\n\n{beat}"
    return {"skill": label, "check": check, "text": text, "damage": damage,
            "roll": roll_line}
