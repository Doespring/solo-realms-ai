"""Пределы подготовки книги: где кончается секция и сколько сущностей на вызов.

Это настройки, а не магия посреди кода: их меняют осознанно и видят в метрике,
во что изменение встало. Переменные окружения читаются на каждый вызов, чтобы
тест мог поменять предел без перезапуска процесса.

`SOLO_PREPARATION_SECTION_CHARACTERS` — сколько символов книги уходит одним
вызовом. Предел выбран по замеру, а не на глаз: на живой книге (256 страниц)
поток ответа занимал до 9,1 байта на символ секции, поэтому 6 000 символов
дают худший ответ ~55 КБ при потолке 98 304 — запас 44 %, а не «ещё чуть-чуть».

r237: цель — 40 000 символов. Книга на 429 тыс. знаков тогда планируется
двузначным числом блоков, а не 278 заготовками; ответ крупного блока, который
не влез в потолок, делится пополам ПО ФАКТУ ответа модели, а не заранее.

`SOLO_PREPARATION_ENTITIES_PER_CALL` — сколько сущностей модель может вернуть за
вызов. Ответ растёт от числа сущностей, а не от размера книги.

`SOLO_PREPARATION_MAX_SPLIT_DEPTH` — сколько раз секцию можно разделить пополам
после потолка ответа (2^3 = 8 частей от исходной).

`SOLO_PREPARATION_STRUCTURE_SPLIT_DEPTH` — сколько раз можно делить секцию из-за
ошибки ФОРМАТА ответа. Число маленькое намеренно: детерминированная ошибка
(два одинаковых key, name длиннее 120, kind вне списка) половинами не лечится,
и глубокое деление стоит денег, ничего не возвращая.

`SOLO_PREPARATION_HEADROOM` — доля потолка, после которой ответ считается
пограничным. Это НЕ повод делить: поток ответа состоит в основном из SSE-
обрамления (~290 байт на событие), и на живой книге здоровый ответ занимал
78–86 КБ из 98 КБ, то есть 80 % при осмысленном содержании. Доля остаётся
только меткой в журнале (`near_byte_limit`); делят по факту отказа — обрыва
по потолку или finish_reason=length.

`SOLO_PREPARATION_HEADING_FLOOR` — какую долю блока нужно набрать, чтобы граница
главы стала приказом, а не предпочтением. Половина: книга из глав по три тысячи
знаков иначе даёт отдельный вызов на главу.

`SOLO_PREPARATION_CONCURRENCY` — сколько секций книги читаются ОДНОВРЕМЕННО.
Секции независимы (каждая видит только свои страницы), поэтому ожидание ответа
модели складывалось впустую: девять секций по 6–9 секунд шли как минута, хотя
могли идти как три. Предел 4 — согласие провайдера и память VPS: шесть
параллельных запросов на одну книгу уже упираются в лимит соединений.
Единица возвращает прежнее поведение (по одной).
"""
import os

#: Мельче этого секцию не дробим: одна страница — предел разумного, дальше
#: честная ошибка с указанием фрагмента, а не бесконечная нарезка.
MIN_CHARACTERS=2000

def _int(name,default,low,high):
    try:value=int(os.environ.get(name,default))
    except (TypeError,ValueError):value=default
    return max(low,min(high,value))

def _ratio(name,default):
    try:value=float(os.environ.get(name,default))
    except (TypeError,ValueError):value=default
    return max(.3,min(.95,value))

def limits():
    """Действующие пределы подготовки. Читаются на каждый вызов."""
    return dict(section_characters=_int('SOLO_PREPARATION_SECTION_CHARACTERS',40000,2000,40000),
        entities_per_call=_int('SOLO_PREPARATION_ENTITIES_PER_CALL',12,1,40),
        max_split_depth=_int('SOLO_PREPARATION_MAX_SPLIT_DEPTH',3,0,6),
        structure_split_depth=_int('SOLO_PREPARATION_STRUCTURE_SPLIT_DEPTH',1,0,3),
        # Целевой запас до потолка ответа: ответ, занявший больше, означает,
        # что секция ещё велика. Потолок при этом не поднимается, а секция делится.
        headroom=_ratio('SOLO_PREPARATION_HEADROOM',.7),
        heading_floor=_ratio('SOLO_PREPARATION_HEADING_FLOOR',.5),
        concurrency=_int('SOLO_PREPARATION_CONCURRENCY',4,1,4),
        min_characters=MIN_CHARACTERS)
